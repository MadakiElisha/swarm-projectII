#!/usr/bin/env python3
"""Create an operating area from OpenStreetMap and a fleet.yaml that flies there.

    python3 scripts/make_area.py eko                       # preset (Lagos Island)
    python3 scripts/make_area.py --list                    # presets
    python3 scripts/make_area.py --bbox 6.44,3.38,6.46,3.40 --name my-area
    python3 scripts/make_area.py --center 6.4541,3.3947 --size 1800 --name marina
    python3 scripts/make_area.py eko --drones 7 --launch 6.4509,3.3918

Writes areas/<name>/area.json and areas/<name>/fleet.yaml. Use the fleet with
    SWARM_FLEET=areas/<name>/fleet.yaml  (simulator, ROS launch files, GCS)
and build the matching Gazebo world with scripts/gz/make_world.py.
OSM data (c) OpenStreetMap contributors, ODbL.
"""
import argparse
import json
import math
import os
import sys
import urllib.parse
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "ros2_ws", "src", "swarm_common"))

from swarm_common.area import PRESETS, from_overpass, save_area, synthetic_city  # noqa: E402
from swarm_common.geo import Origin  # noqa: E402

PAD_M = 15.0          # > 2 x safety radius: simultaneous take-offs keep separation
OVERPASS = os.environ.get("OVERPASS_URL", "https://overpass-api.de/api/interpreter")


def fetch_osm(bbox):
    s, w, n, e = bbox
    b = f"{s},{w},{n},{e}"
    q = f"""[out:json][timeout:180];
(
  way["building"]({b});
  relation["building"]({b});
  way["natural"="water"]({b});
  way["waterway"="riverbank"]({b});
  way["landuse"="reservoir"]({b});
  way["highway"]({b});
);
out geom;"""
    data = urllib.parse.urlencode({"data": q}).encode()
    req = urllib.request.Request(OVERPASS, data=data, headers={"User-Agent": "swarm-projectII/0.2"})
    with urllib.request.urlopen(req, timeout=240) as r:
        return json.loads(r.read().decode())


def fleet_yaml(area, n, name, launch_ll=None):
    o = Origin(*area["origin"])
    lx, ly = area["launch"]
    if launch_ll:
        lx, ly = o.to_enu(*launch_ll)
    cols = max(1, int(math.ceil(math.sqrt(n))))
    lines = [f"# Generated by scripts/make_area.py for area '{name}'.",
             "# Launch pad: drones 15 m apart on open ground found in the OSM data.",
             "swarm:",
             f"  origin: {{lat: {o.lat:.6f}, lon: {o.lon:.6f}}}",
             "  area_file: area.json",
             "  geofence: {radius_m: 3000.0, max_alt_m: 120.0}",
             "drones:"]
    for i in range(n):
        x = lx + (i % cols - (cols - 1) / 2) * PAD_M
        y = ly + (i // cols) * PAD_M
        lat, lon = o.to_latlon(x, y)
        lines.append(f"  - {{id: {i + 1}, home_lat: {lat:.7f}, home_lon: {lon:.7f}, "
                     f"mavlink_url: \"tcp:127.0.0.1:{5770 + 10 * i}\"}}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("preset", nargs="?", default=None)
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--bbox", help="south,west,north,east")
    ap.add_argument("--center", help="lat,lon")
    ap.add_argument("--size", type=float, default=1800.0, help="square side in metres (with --center)")
    ap.add_argument("--name")
    ap.add_argument("--drones", type=int, default=5)
    ap.add_argument("--launch", help="lat,lon of the launch pad (default: open ground nearest the centre)")
    ap.add_argument("--osm-json", help="use a saved Overpass response instead of downloading")
    ap.add_argument("--synthetic", action="store_true",
                    help="no download: a generated grid city (streets, blocks, a few towers) for offline tests")
    a = ap.parse_args()
    if a.synthetic:
        name = a.name or "grid-city"
        out_dir = os.path.join(ROOT, "areas", name)
        os.makedirs(out_dir, exist_ok=True)
        area = synthetic_city(blocks=8, block_m=110.0, street_m=30.0, seed=3)
        area["name"] = name
        save_area(area, os.path.join(out_dir, "area.json"))
        with open(os.path.join(out_dir, "fleet.yaml"), "w") as f:
            f.write(fleet_yaml(area, a.drones, name, None))
        print(f"synthetic area '{name}': {len(area['buildings'])} buildings, {len(area['roads'])} streets -> {out_dir}")
        return
    if a.list:
        for k, v in PRESETS.items():
            print(f"{k:16s} {v[4]}")
        return
    if a.bbox:
        bbox = tuple(float(v) for v in a.bbox.split(","))
        name = a.name or "custom"
    elif a.center:
        lat, lon = (float(v) for v in a.center.split(","))
        o, h = Origin(lat, lon), a.size / 2
        s, w = o.to_latlon(-h, -h)
        n, e = o.to_latlon(h, h)
        bbox, name = (s, w, n, e), a.name or "custom"
    else:
        key = a.preset or "eko"
        if key not in PRESETS:
            ap.error(f"unknown preset {key!r}; see --list")
        bbox, name = PRESETS[key][:4], a.name or key
    out_dir = os.path.join(ROOT, "areas", name)
    os.makedirs(out_dir, exist_ok=True)
    if a.osm_json:
        osm = json.load(open(a.osm_json))
    else:
        print(f"fetching OpenStreetMap data for {name} {bbox} ...", flush=True)
        osm = fetch_osm(bbox)
        json.dump(osm, open(os.path.join(out_dir, "osm.json"), "w"))
    area = from_overpass(osm, name, bbox)
    save_area(area, os.path.join(out_dir, "area.json"))
    launch = tuple(float(v) for v in a.launch.split(",")) if a.launch else None
    with open(os.path.join(out_dir, "fleet.yaml"), "w") as f:
        f.write(fleet_yaml(area, a.drones, name, launch))
    o = Origin(*area["origin"])
    ll = o.to_latlon(*area["launch"])
    print(f"{len(area['buildings'])} buildings (tallest {area['max_h']:.0f} m), {len(area['water'])} water, "
          f"{len(area['roads'])} roads")
    print(f"launch pad: {ll[0]:.6f},{ll[1]:.6f}  -> {out_dir}/fleet.yaml")
    print(f"next: SWARM_FLEET={os.path.relpath(out_dir, ROOT)}/fleet.yaml python3 scripts/gz/make_world.py")


if __name__ == "__main__":
    main()
